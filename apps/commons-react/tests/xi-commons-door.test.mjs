import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PORTALS } from "../src/commonsPortalRegistry.mjs";
import { XI_COLLABORATION_DOOR, reviewedXiCollaborationDoor } from "../src/xiCommonsDoor.mjs";
test("verified public HTTPS website never becomes a fifth story world or a Xi protocol grant",()=>{
  const d=reviewedXiCollaborationDoor();
  assert.equal(PORTALS.length,4);
  assert.ok(!PORTALS.some(p=>p.id===d.id));
  assert.equal(d.href,"https://michaelwave369.github.io/xi-vessel-bridge/");
  assert.equal(d.sourceUrl,"https://github.com/MichaelWave369/xi-vessel-bridge");
  assert.equal(d.status,"PUBLIC_STATIC_WEBSITE_VERIFIED");
  assert.equal(d.proofRunUrl,"https://github.com/MichaelWave369/xi-vessel-bridge/actions/runs/40243474173");
  assert.match(d.manifestSha256,/^[a-f0-9]{64}$/);
  assert.equal(d.liveXiConnected,false);
  assert.equal(d.authorizationGranted,false);
  assert.equal(d.externalPilot,"BLOCKED");
  assert.equal(d.realTwoHostTest,"NOT_RUN");
  assert.equal(d.requiresUserNavigation,true);
  assert.equal(d.fictionWorld,false);
  assert.ok(Object.isFrozen(XI_COLLABORATION_DOOR));
});
test("Commons UI exposes both external links only on deliberate click",()=>{
  const jsx=readFileSync(new URL("../src/CommonsNexus.jsx",import.meta.url),"utf8");
  assert.match(jsx,/className="xi-commons-door"/);
  assert.match(jsx,/href=\{reviewedXiCollaborationDoor\(\)\.href\}/);
  assert.match(jsx,/href=\{reviewedXiCollaborationDoor\(\)\.sourceUrl\}/);
  assert.match(jsx,/target="_blank" rel="noopener noreferrer"/);
  assert.match(jsx,/not a fifth fictional world/);
  assert.match(jsx,/TWO HOST TEST NOT RUN/);
  assert.match(jsx,/Only the public static website is verified/);
  assert.doesNotMatch(jsx,/\bfetch\(reviewedXiCollaborationDoor/);
});
